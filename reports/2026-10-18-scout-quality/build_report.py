def read_json(path):
    return json.loads(path.read_text())


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def api(path):
    return subprocess.check_output([
        "gh", "api", f"repos/{REPO}/{path}",
        "-H", "Accept: application/vnd.github.raw+json",
    ])


def download_inputs(root):
    summary_path = "reports/2026-10-16-progress/summary.json"
    summary = json.loads(api(f"contents/{summary_path}?ref={REPORT_COMMIT}"))
    if summary["data_commit"] != DATA_COMMIT:
        raise ValueError("Unexpected baseline data commit")
    tree = json.loads(api(f"git/trees/{DATA_COMMIT}?recursive=1"))["tree"]
    blobs = {item["path"]: item for item in tree if item["type"] == "blob"}
    jobs = []
    for trace in summary["traces"]:
        run = trace["scout_run_id"]
        selected = next(item for item in trace["selected_runs"] if item["run_id"] == run)
        directory = root / "baseline" / trace["ref"]
        prefix = f"data/teammate-traces/runs/{run}/"
        jobs.extend(
            (path, directory / Path(path).name)
            for path in blobs
            if path.startswith(prefix) and path.endswith(".prompt.txt")
        )
        jobs.extend(
            (f"data/teammate-traces/{path}", directory / name)
            for path, name in (
                (trace["transcript_file"], "transcript.txt"),
                (trace["report_file"], "report.json"),
                (selected["file"], "run.json"),
            )
        )

    def download(job):
        source, target = job
        data = api(f"contents/{source}?ref={DATA_COMMIT}")
        blob = hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest()
        if blob != blobs[source]["sha"]:
            raise ValueError(f"Git blob checksum mismatch: {source}")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        return {
            "source_path": source,
            "local_path": str(target.relative_to(root)),
            "git_blob_sha": blob,
            "sha256": hashlib.sha256(data).hexdigest(),
            "bytes": len(data),
        }

    root.mkdir(parents=True, exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        files = list(pool.map(download, jobs))
    write_json(root / "inputs.json", {
        "data_commit": DATA_COMMIT,
        "report_commit": REPORT_COMMIT,
        "files": sorted(files, key=lambda item: item["local_path"]),
    })
    write_json(root / "baseline-summary.json", summary)


def verify_inputs(root):
    manifest = read_json(root / "inputs.json")
    if manifest["data_commit"] != DATA_COMMIT or manifest["report_commit"] != REPORT_COMMIT:
        raise ValueError("Baseline provenance mismatch")
    for entry in manifest["files"]:
        data = (root / entry["local_path"]).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if digest != entry["sha256"] or len(data) != entry["bytes"]:
            raise ValueError(f"Input checksum mismatch: {entry['local_path']}")
        blob = hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest()
        if blob != entry["git_blob_sha"]:
            raise ValueError(f"Input Git blob mismatch: {entry['local_path']}")
    return manifest


def valid_confidence(value):
    return type(value) in (int, float) and math.isfinite(value) and 0 <= value <= 1


def annotation_errors(annotations, report, directory):
    errors = []
    messages = {item["index"]: item for item in report["messages"]}
    numbers = [item.get("message_number") for item in annotations]
    if numbers != sorted(messages):
        errors.append("Annotation sequence/coverage differs from original message order")
    roster = {item["id"] for item in report["participants"]}
    for annotation in annotations:
        number = annotation.get("message_number")
        prefix = f"turn {number}: "
        if number not in messages:
            errors.append(prefix + "unknown target")
            continue
        prompt = (directory / f"message-{number}.prompt.txt").read_text()
        earlier = {
            int(match) for match in re.findall(r"(?m)^#(\d+) .+ \([^\n]*\):", prompt)
            if int(match) < number
        }
        primary = annotation.get("primary_type")
        secondary = annotation.get("secondary_types", [])
        if primary not in TYPES:
            errors.append(prefix + "invalid primary type")
        if (len(secondary) > 2 or len(set(secondary)) != len(secondary)
                or primary in secondary or any(item not in TYPES for item in secondary)):
            errors.append(prefix + "invalid secondary types")
        replies = annotation.get("replies_to", [])
        if any(type(value) is not int or value not in earlier for value in replies):
            errors.append(prefix + "reply outside supplied earlier context")
        if any(value not in roster for value in annotation.get("addressed_to", [])):
            errors.append(prefix + "addressee outside roster")
        if not valid_confidence(annotation.get("confidence")):
            errors.append(prefix + "invalid confidence")
        if type(annotation.get("ambiguous")) is not bool:
            errors.append(prefix + "invalid ambiguous flag")
        rationale = annotation.get("rationale", "")
        if not isinstance(rationale, str) or len(rationale) > 500:
            errors.append(prefix + "invalid rationale")
        evidence = annotation.get("evidence", [])
        if len(evidence) > 3:
            errors.append(prefix + "more than three evidence spans")
        target = messages[number]["text"].strip()[:8000]
        for item in evidence:
            text = item.get("text")
            if not isinstance(text, str) or not text or text not in target:
                errors.append(prefix + "non-verbatim or out-of-bounds evidence")
    return errors


def finding_errors(findings, directory):
    errors = []
    if len(findings) != 3 or {item.get("category") for item in findings} != set(CATEGORIES):
        errors.append("Exactly one finding per category is required")
    prompt = (directory / "collaboration.prompt.txt").read_text()
    originals = [int(value) for value in re.findall(r"AgentTrace turn #(\d+); agent ", prompt)]
    if not originals:
        raise ValueError(f"No candidate turn map in {directory}")
    allowed = set(originals)
    for finding in findings:
        category = finding.get("category")
        numbers = finding.get("message_numbers", [])
        if type(finding.get("found")) is not bool or not valid_confidence(finding.get("confidence")):
            errors.append(f"{category}: invalid boolean or confidence")
        if any(type(number) is not int or number not in allowed for number in numbers):
            errors.append(f"{category}: turn outside supplied candidates")
        if finding.get("found") and not numbers:
            errors.append(f"{category}: positive without evidence turns")
        citations = [int(value) for value in re.findall(r"\[M(\d+)\]", finding.get("explanation", ""))]
        if not citations:
            errors.append(f"{category}: no explanation citations")
        elif any(not 1 <= value <= len(originals) for value in citations):
            errors.append(f"{category}: invalid display-label citation")
        elif any(originals[value - 1] not in numbers for value in citations):
            errors.append(f"{category}: explanation citations not represented in original turn numbers")
    return errors


def audit_outcome(label, found):
    if label == "supported_positive":
        return "audit_agree_positive" if found else "audit_possible_false_negative"
    if label == "supported_negative":
        return "audit_possible_false_positive" if found else "audit_agree_negative"
    return "excluded_" + label


def compare(root):
    manifest = verify_inputs(root)
    summary = read_json(root / "baseline-summary.json")
    audit = read_json(HERE / "audit.json")
    provenance = read_json(HERE / "replay-provenance.json")
    if (provenance["requested_model"] != "gpt-6.1-sol"
            or provenance["native_scout_run"] is not False
            or len(provenance["agents"]) != 9
            or {item["ref"] for item in provenance["agents"]} != set(REFERENCES)
            or any(item["model"] != "gpt-6.1-sol" for item in provenance["agents"])):
        raise ValueError("Replay execution provenance mismatch")
    cases = {(item["ref"], item["category"]): item for item in audit["cases"]}
    expected = {(ref, category) for ref in REFERENCES for category in CATEGORIES}
    if set(cases) != expected or len(audit["cases"]) != 27:
        raise ValueError("Audit must cover all 27 trace/category cells exactly once")
    traces, annotation_pairs, cells = [], [], []
    validation = {"baseline": {}, "replay": {}}
    repairs = []
    for trace in summary["traces"]:
        ref = trace["ref"]
        directory = root / "baseline" / ref
        baseline = read_json(directory / "run.json")
        report = read_json(directory / "report.json")
        replay = read_json(HERE / "replays" / f"{ref}.json")
        if (baseline["id"] != trace["scout_run_id"]
                or baseline["trace_id"] != trace["trace_id"]
                or baseline["provenance"]["model"] != "openai/gpt-5.4-mini"):
            raise ValueError(f"{ref}: baseline provenance mismatch")
        if (replay["trace_ref"] != ref or replay["model"] != "gpt-6.1-sol"
                or replay["native_scout_run"] is not False):
            raise ValueError(f"{ref}: replay provenance mismatch")
        validation["baseline"][ref] = (
            annotation_errors(baseline["output"]["annotations"], report, directory)
            + finding_errors(baseline["output"]["findings"], directory)
        )
        validation["replay"][ref] = (
            annotation_errors(replay["annotations"], report, directory)
            + finding_errors(replay["findings"], directory)
        )
        if validation["replay"][ref]:
            raise ValueError(f"{ref}: replay validation errors: {validation['replay'][ref]}")
        initial_path = HERE / "replays" / f"{ref}.initial.json"
        if replay.get("output_repair") and not initial_path.exists():
            raise ValueError(f"{ref}: repaired replay is missing its original output")
        if initial_path.exists():
            initial = read_json(initial_path)
            initial_errors = (
                annotation_errors(initial["annotations"], report, directory)
                + finding_errors(initial["findings"], directory)
            )
            repair = replay.get("output_repair")
            if not repair or not initial_errors:
                raise ValueError(f"{ref}: undocumented or unnecessary replay repair")
            before = dict(initial)
            after = {key: value for key, value in replay.items() if key != "output_repair"}
            before["annotations"] = [
                {key: value for key, value in item.items() if key != "addressed_to"}
                for item in before["annotations"]
            ]
            after["annotations"] = [
                {key: value for key, value in item.items() if key != "addressed_to"}
                for item in after["annotations"]
            ]
            if before != after:
                raise ValueError(f"{ref}: repair changed more than addressee identifiers")
            repairs.append({"ref": ref, "initial_errors": initial_errors, "repair": repair})
        original_annotations = {item["message_number"]: item for item in baseline["output"]["annotations"]}
        replay_annotations = {item["message_number"]: item for item in replay["annotations"]}
        operator_numbers = {1}
        if ref == "E6":
            operator_numbers.add(5)
        if ref == "E9":
            operator_numbers.add(9)
        for number, original in original_annotations.items():
            new = replay_annotations[number]
            annotation_pairs.append({
                "ref": ref,
                "message_number": number,
                "operator_post": number in operator_numbers,
                "baseline_primary": original["primary_type"],
                "replay_primary": new["primary_type"],
                "same_primary": original["primary_type"] == new["primary_type"],
                "baseline_secondary": original["secondary_types"],
                "replay_secondary": new["secondary_types"],
                "baseline_type_in_replay_labels": original["primary_type"] in (
                    {new["primary_type"]} | set(new["secondary_types"])
                ),
                "baseline_replies": original["replies_to"],
                "replay_replies": new["replies_to"],
                "same_reply_set": set(original["replies_to"]) == set(new["replies_to"]),
                "baseline_addressees": original["addressed_to"],
                "replay_addressees": new["addressed_to"],
                "same_addressee_set": set(original["addressed_to"]) == set(new["addressed_to"]),
            })
        original_findings = {item["category"]: item for item in baseline["output"]["findings"]}
        replay_findings = {item["category"]: item for item in replay["findings"]}
        for category in CATEGORIES:
            before, after = original_findings[category], replay_findings[category]
            case = cases[(ref, category)]
            cells.append({
                "ref": ref, "label": trace["label"], "category": category,
                "baseline": before, "replay": after, "changed": before["found"] != after["found"],
                "audit": case,
                "baseline_audit_outcome": audit_outcome(case["label"], before["found"]),
                "replay_audit_outcome": audit_outcome(case["label"], after["found"]),
            })
        scout = next(item for item in trace["selected_runs"] if item["run_id"] == trace["scout_run_id"])
        traces.append({
            "ref": ref, "label": trace["label"], "trace_id": trace["trace_id"],
            "baseline_run_id": baseline["id"], "baseline_provenance": baseline["provenance"],
            "baseline_coverage": baseline["output"]["coverage"],
            "transcript_url": source_url(trace["transcript_file"]),
            "baseline_run_url": source_url(scout["file"]),
            "baseline_prompt_url": source_url(f"runs/{baseline['id']}/collaboration.prompt.txt"),
            "replay_file": f"replays/{ref}.json",
        })
    all_pairs = annotation_pairs
    agent_pairs = [item for item in all_pairs if not item["operator_post"]]
    operator_pairs = [item for item in all_pairs if item["operator_post"]]

    def pair_stats(pairs):
        return {
            "count": len(pairs),
            "same_primary": sum(item["same_primary"] for item in pairs),
            "different_primary": sum(not item["same_primary"] for item in pairs),
            "same_reply_set": sum(item["same_reply_set"] for item in pairs),
            "same_addressee_set": sum(item["same_addressee_set"] for item in pairs),
            "different_primary_but_baseline_in_replay_secondary": sum(
                not item["same_primary"] and item["baseline_type_in_replay_labels"] for item in pairs
            ),
            "baseline_primary_counts": dict(collections.Counter(item["baseline_primary"] for item in pairs)),
            "replay_primary_counts": dict(collections.Counter(item["replay_primary"] for item in pairs)),
        }

    category_stats = {}
    for category in CATEGORIES:
        selected = [item for item in cells if item["category"] == category]
        category_stats[category] = {
            "judgments": len(selected),
            "baseline_positive": sum(item["baseline"]["found"] for item in selected),
            "replay_positive": sum(item["replay"]["found"] for item in selected),
            "true_to_false": sum(item["baseline"]["found"] and not item["replay"]["found"] for item in selected),
            "false_to_true": sum(not item["baseline"]["found"] and item["replay"]["found"] for item in selected),
            "same": sum(not item["changed"] for item in selected),
        }
    result = {
        "schema": "agenttrace/scout-prompt-replay-comparison.v1",
        "date": "2026-10-18",
        "baseline_model": "openai/gpt-5.4-mini",
        "replay_model": "gpt-6.1-sol",
        "execution": "Copilot agent prompt replay, not a native Inspect Scout provider run",
        "data_commit": DATA_COMMIT, "baseline_report_commit": REPORT_COMMIT,
        "counts": {
            "traces": len(traces), "annotations": len(all_pairs),
            "agent_annotations": len(agent_pairs), "operator_annotations": len(operator_pairs),
            "category_judgments": len(cells), "same_category_boolean": sum(not item["changed"] for item in cells),
            "baseline_positive": sum(item["baseline"]["found"] for item in cells),
            "replay_positive": sum(item["replay"]["found"] for item in cells),
        },
        "category_stats": category_stats,
        "annotation_stats": {
            "all_posts": pair_stats(all_pairs),
            "agent_only": pair_stats(agent_pairs),
            "operator_only": pair_stats(operator_pairs),
        },
        "audit_label_counts": dict(collections.Counter(item["label"] for item in audit["cases"])),
        "audit_outcome_counts": {
            version: dict(collections.Counter(item[f"{version}_audit_outcome"] for item in cells))
            for version in ("baseline", "replay")
        },
        "validation": validation,
        "explicit_replay_repairs": repairs,
        "replay_output_sha256": {
            path.name: hashlib.sha256(path.read_bytes()).hexdigest()
            for path in sorted((HERE / "replays").glob("*.json"))
        },
        "audit_sha256": hashlib.sha256((HERE / "audit.json").read_bytes()).hexdigest(),
        "replay_provenance_sha256": hashlib.sha256((HERE / "replay-provenance.json").read_bytes()).hexdigest(),
        "traces": traces,
        "cells": cells,
        "annotation_pairs": annotation_pairs,
        "limitations": [
            "Prompt replay is not a native Scout provider run and does not isolate model identity from harness effects.",
            "Agent/system instructions, tools, and generation settings differ; original native generation-event/token logs are unavailable.",
            "Message prompts were processed chronologically within one agent per trace, retaining additional earlier context.",
            "Collaboration prompts retain baseline annotations and candidates; replayed message labels did not regenerate candidate sets.",
            "Collaboration agents had already seen message-annotation prompts, including some text outside the bounded collaboration prompt.",
            "Eight baseline traces use analyzer 2.1.0 / prompt 3; E7 uses 2.0.0 / prompt 2.",
            "Both versions retain 11 task/operator posts in their 70 annotation targets; actual-agent results are also separated.",
            "A single non-blind AI audit is not independent human ground truth; no validated precision, recall, false-positive rate, or false-negative rate is estimated.",
            "Solo and task-only conditions are not clean negative collaboration examples; they are excluded from audit error counts.",
            "One replay per prompt, no seeds or repeated sampling; confidence is model-reported and uncalibrated.",
            "Raw E2 replay used short instance IDs in seven addressee lists. The initial output is retained; full roster IDs were explicitly repaired without changing classifications or findings.",
        ],
    }
    if result["counts"]["annotations"] != 70 or len(agent_pairs) != 59 or len(cells) != 27:
        raise ValueError("Unexpected cohort coverage")
    if sum(item["baseline"]["found"] for item in cells) != 16:
        raise ValueError("Baseline differs from the selected progress report")
    return result, manifest


def source_url(relative):
    return f"https://github.com/{REPO}/blob/{DATA_COMMIT}/data/teammate-traces/{relative}"


def escape(value):
    return html.escape(str(value), quote=True)


def link(url, text):
    return f'<a href="{escape(url)}">{escape(text)}</a>'


def tag(value):
    return '<span class="flag yes">Flag</span>' if value else '<span class="flag no">No flag</span>'


def table(headers, rows):
    head = "".join(f"<th>{escape(value)}</th>" for value in headers)
    body = "".join("<tr>" + "".join(f"<td>{value}</td>" for value in row) + "</tr>" for row in rows)
    return f'<div class="table-wrap"><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>'


